#!/usr/bin/env python3
"""Turn the matrix journals into the paper's per-factor tables and macros.

One table per reviewer ask -- graded sensitivity, autonomy, architecture, crew
model -- each reporting its numbers against *its own* calibrated permutation
null rather than against 0.5, because the protocol's floor sits near 0.57 and a
bare AUC is not interpretable without it.

House style, applied throughout: report a trend or a paired difference rather
than a bare point estimate; report both estimators where they disagree; and say
plainly what the evidence does not support. Three crew deployments cannot
support a scaling law and this script does not pretend otherwise -- it reports
an ordering and one pre-declared contrast.
"""

